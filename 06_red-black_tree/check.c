#include "struct.h"
#include <limits.h>

/* ================================================================
 *  check_red_children
 *  ------------------
 *  Рекурсивно проверяет, что у КРАСНОГО узла нет КРАСНЫХ детей.
 *  Возвращает 0, если всё ок, и -1 при нарушении.
 * ================================================================ */
int check_red_children(RBNode *root) {
    if (root == NULL) return 0;

    /* Если текущий узел красный, его дети обязаны быть чёрными (или NULL) */
    if (root->color == 1) {
        if (root->left != NULL && root->left->color == 1) {
            return -1; /* Ошибка: красный левый ребёнок у красного родителя */
        }
        if (root->right != NULL && root->right->color == 1) {
            return -1; /* Ошибка: красный правый ребёнок у красного родителя */
        }
    }

    /* Рекурсивно проверяем левое и правое поддеревья */
    if (check_red_children(root->left) == -1)  return -1;
    if (check_red_children(root->right) == -1) return -1;

    return 0;
}

/* ================================================================
 *  check_black_height
 *  ------------------
 *  Рекурсивно считает чёрную высоту поддеревьев и проверяет их баланс.
 *  Возвращает:
 *    >= 0 — корректная чёрная высота данного поддерева.
 *    -1   — если чёрные высоты левого и правого поддеревьев не совпали.
 * ================================================================ */
int check_black_height(RBNode *root) {
    if (root == NULL) {
        /* В КЧД без NIL-заглушек сам указатель NULL считается чёрным листом,
         * но его вклад в высоту пути оценивается как 0. */
        return 0; 
    }

    int bhl = check_black_height(root->left);
    int bhr = check_black_height(root->right);

    /* Если в каком-то поддереве уже найдена ошибка баланса, прокидываем её вверх */
    if (bhl == -1 || bhr == -1) return -1;

    /* Чёрная высота левой и правой ветви ОБЯЗАНА совпадать */
    if (bhl != bhr) return -1;

    /* Возвращаем высоту поддерева: высота детей + 1 (если текущий узел чёрный) */
    return bhl + (root->color == 0 ? 1 : 0);
}

/* ================================================================
 *  check_bst_property
 *  ------------------
 *  Проверяет, упорядочены ли ключи по правилам BST (Binary Search Tree).
 *  Использует диапазон допустимых значений [min_val, max_val] во избежание
 *  ошибок, когда проверяется только локальный родитель и его дети.
 * ================================================================ */
int check_bst_property(RBNode *root, long long min_val, long long max_val) {
    if (root == NULL) return 0;

    /* Ключ должен строго укладываться в границы, заданные предками */
    if (root->key <= min_val || root->key >= max_val) {
        return -1; /* Ошибка: нарушено свойство сортировки BST */
    }

    /* Для левого ребенка текущий ключ становится верхней границей.
     * Для правого ребенка текущий ключ становится нижней границей. */
    if (check_bst_property(root->left, min_val, root->key) == -1) return -1;
    if (check_bst_property(root->right, root->key, max_val) == -1) return -1;

    return 0;
}

/* ================================================================
 *  is_valid_rbt
 *  ------------
 *  Главная публичная функция проверки структуры КЧД.
 *  Возвращает 0, если дерево полностью валидно, и -1, если есть ошибки.
 * ================================================================ */
int is_valid_rbt(RBNode *root) {
    /* Свойство 0: Пустое дерево всегда валидно */
    if (root == NULL) return 0;

    /* Свойство 1: Корень дерева обязан быть ЧЁРНЫМ (0) */
    if (root->color == 1) {
        return -1;
    }

    /* Свойство 2: Проверка отсутствия двух красных узлов подряд */
    if (check_red_children(root) == -1) {
        return -1;
    }

    /* Свойство 3: Проверка равенства чёрной высоты для всех путей */
    int bh = check_black_height(root);
    if (bh == -1) {
        return -1;
    }

    /* Свойство 4: Проверка корректности BST (сортировки ключей) */
    /* Используем LLONG_MIN и LLONG_MAX, чтобы избежать overflow при граничных int */
    if (check_bst_property(root, LLONG_MIN, LLONG_MAX) == -1) {
        return -1;
    }

    /* Если всё прошло успешно, выводим текущую чёрную высоту дерева */
    return bh;
}