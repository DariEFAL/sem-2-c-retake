/* ================================================================
 *  rotate_left
 *  -----------
 *  Левый поворот вокруг узла x. Узел y (правый ребёнок x) встаёт на место x.
 * ================================================================ */
void rotate_left(RBNode **root, RBNode *x) {
    if (root == NULL || x == NULL || x->right == NULL) return;

    RBNode *y = x->right;          /* Запоминаем правого ребёнка */
    x->right = y->left;            /* Левое поддерево y становится правым поддеревом x */

    if (y->left != NULL) 
        y->left->parent = x;       /* Обновляем родителя для перевешенного поддерева */

    y->parent = x->parent;         /* y занимает место x в иерархии родителей */

    if (x->parent == NULL) 
        *root = y;                 /* Если x был корнем, то y становится новым корнем */
    else if (x == x->parent->left) 
        x->parent->left = y;       /* Если x был левым ребёнком */
    else
        x->parent->right = y;      /* Если x был правым ребёнком */

    y->left = x;                   /* x становится левым ребёнком y */
    x->parent = y;                 /* Родителем x теперь является y */
}

/* ================================================================
 *  rotate_right
 *  ------------
 *  Правый поворот вокруг узла x. Узел y (левый ребёнок x) встаёт на место x.
 * ================================================================ */
void rotate_right(RBNode **root, RBNode *x) {
    if (root == NULL || x == NULL || x->left == NULL) return;

    RBNode *y = x->left;           /* Запоминаем левого ребёнка */
    x->left = y->right;            /* Правое поддерево y становится левым поддеревом x */

    if (y->right != NULL) 
        y->right->parent = x;      /* Обновляем родителя для перевешенного поддерева */

    y->parent = x->parent;         /* y занимает место x в иерархии родителей */

    if (x->parent == NULL)
        *root = y;                 /* Если x был корнем, то y становится новым корнем */
    else if (x == x->parent->left) /* ФИКСИРОВАННЫЙ БАГ: проверка x == x_parent->left */
        x->parent->left = y;
    else
        x->parent->right = y;

    y->right = x;                  /* x становится правым ребёнком y */
    x->parent = y;                 /* Родителем x теперь является y */
}