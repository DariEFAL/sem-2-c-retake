// Объединение (слияние) ребенка c[i] и ребенка c[i+1] узла x.
// Разделяющий ключ из родителя x опускается вниз и склеивает детей.
void B_Tree_Merge(BTreeNode *x, int i) {
    BTreeNode *y = x->c[i];      // Левый ребенок
    BTreeNode *z = x->c[i + 1];  // Правый ребенок
    
    // Вытаскиваем разделяющий ключ из родителя x и ставим в конец узла y
    y->keys[T - 1] = x->keys[i];
    
    // Копируем все ключи из правого узла z в конец левого узла y
    for (int j = 0; j < z->n; j++) {
        y->keys[j + T] = z->keys[j];
    }
    
    // Если узлы не листья, переносим также и указатели на детей из z в y
    if (!y->leaf) {
        for (int j = 0; j <= z->n; j++) {
            y->c[j + T] = z->c[j];
        }
    }
    // Теперь узел y содержит максимум ключей (2t - 1)
    y->n = 2 * T - 1;
    
    // В родительском узле x сдвигаем оставшиеся ключи и детей влево,
    // так как один ключ ушел вниз, а ребенок z уничтожен
    for (int j = i; j < x->n - 1; j++) {
        x->keys[j] = x->keys[j + 1];
    }
    for (int j = i + 1; j < x->n; j++) {
        x->c[j] = x->c[j + 1];
    }
    x->n--; // Ключей у родителя стало меньше
    free(z); // Полностью освобождаем память от удаленного узла z
}

// Случай 3a (Вращение вправо): заимствование ключа у левого соседа (sibling) для узла child
void B_Tree_Borrow_Prev(BTreeNode *x, int i) {
    BTreeNode *child = x->c[i];
    BTreeNode *sibling = x->c[i - 1];
    
    // В узле child освобождаем самое первое место: сдвигаем все ключи и детей вправо
    for (int j = child->n - 1; j >= 0; j--) {
        child->keys[j + 1] = child->keys[j];
    }
    if (!child->leaf) {
        for (int j = child->n; j >= 0; j--) {
            child->c[j + 1] = child->c[j];
        }
    }
    
    // Ключ из родителя x опускается в самое начало узла child
    child->keys[0] = x->keys[i - 1];
    
    // Важнейший шаг: крайний правый ребенок левого соседа отвязывается
    // и привязывается как самый первый (левый) ребенок к узлу child
    if (!child->leaf) {
        child->c[0] = sibling->c[sibling->n];
    }
    
    // Последний ключ левого соседа поднимается в родителя x взамен опущенного
    x->keys[i - 1] = sibling->keys[sibling->n - 1];
    
    child->n++;
    sibling->n--;
}

// Случай 3a (Вращение влево): заимствование ключа у правого соседа (sibling) для узла child
void B_Tree_Borrow_Next(BTreeNode *x, int i) {
    BTreeNode *child = x->c[i];
    BTreeNode *sibling = x->c[i + 1];
    
    // Ключ из родителя x опускается в самый конец узла child
    child->keys[child->n] = x->keys[i];
    
    // Первый (левый) ребенок правого соседа отвязывается от него 
    // и привязывается в самый конец списка детей узла child
    if (!child->leaf) {
        child->c[child->n + 1] = sibling->c[0];
    }
    
    // Самый первый ключ правого соседа поднимается к родителю x
    x->keys[i] = sibling->keys[0];
    
    // У правого соседа сдвигаем все оставшиеся ключи и детей влево на освободившиеся места
    for (int j = 1; j < sibling->n; j++) {
        sibling->keys[j - 1] = sibling->keys[j];
    }
    if (!sibling->leaf) {
        for (int j = 1; j <= sibling->n; j++) {
            sibling->c[j - 1] = sibling->c[j];
        }
    }
    
    child->n++;
    sibling->n--;
}

// Обеспечение того, чтобы у ребенка c[i] было минимум t ключей перед тем, как зайти в него
void B_Tree_Fill(BTreeNode *x, int i) {
    // Если левый сосед богатый — занимаем у него
    if (i != 0 && x->c[i - 1]->n >= T) {
        B_Tree_Borrow_Prev(x, i);
    } 
    // Если правый сосед богатый — занимаем у него
    else if (i != x->n && x->c[i + 1]->n >= T) {
        B_Tree_Borrow_Next(x, i);
    } 
    // Если оба соседа бедные — сливаем узлы
    else {
        if (i != x->n) {
            B_Tree_Merge(x, i); // Сливаем с правым
        } else {
            B_Tree_Merge(x, i - 1); // Сливаем с левым
        }
    }
}

// Нахождение предшественника (самого большого ключа в левом поддереве)
int B_Tree_Get_Pred(BTreeNode *x) {
    BTreeNode *cur = x;
    // Просто всегда идем в самого крайнего правого ребенка, пока не дойдем до листа
    while (!cur->leaf) {
        cur = cur->c[cur->n];
    }
    return cur->keys[cur->n - 1]; // Возвращаем последний ключ листа
}

// Нахождение преемника (самого маленького ключа в правом поддереве)
int B_Tree_Get_Succ(BTreeNode *x) {
    BTreeNode *cur = x;
    // Всегда идем в самого крайнего левого ребенка (индекс 0) до листа
    while (!cur->leaf) {
        cur = cur->c[0];
    }
    return cur->keys[0]; // Возвращаем первый ключ листа
}

// Рекурсивное удаление ключа k из поддерева узла x
void B_Tree_Delete_Internal(BTreeNode *x, int k) {
    int i = 0;
    // Находим позицию ключа или место спуска
    while (i < x->n && k > x->keys[i]) {
        i++;
    }
    
    // Если ключ k найден прямо в текущем узле x
    if (i < x->n && k == x->keys[i]) {
        // Случай 1: Узел является листом. Просто удаляем ключ со сдвигом элементов.
        if (x->leaf) {
            for (int j = i + 1; j < x->n; j++) {
                x->keys[j - 1] = x->keys[j];
            }
            x->n--;
        } else {
            // Случай 2: Ключ во внутреннем узле
            BTreeNode *y = x->c[i];     // Левый ребенок
            BTreeNode *z = x->c[i + 1]; // Правый ребенок
            
            // Случай 2a: Левый ребенок имеет запас ключей
            if (y->n >= T) {
                int pred = B_Tree_Get_Pred(y); // Находим предшественника
                x->keys[i] = pred;             // Заменяем удаляемый ключ на предшественника
                B_Tree_Delete_Internal(y, pred); // Рекурсивно стираем предшественника внизу
            } 
            // Случай 2b: Правый ребенок имеет запас ключей
            else if (z->n >= T) {
                int succ = B_Tree_Get_Succ(z); // Находим преемника
                x->keys[i] = succ;             // Заменяем удаляемый ключ на преемника
                B_Tree_Delete_Internal(z, succ); // Рекурсивно стираем преемника внизу
            } 
            // Случай 2c: Оба ребенка бедные. Сливаем их вместе с ключом k.
            else {
                B_Tree_Merge(x, i);
                B_Tree_Delete_Internal(y, k); // Удаляем k из объединенного узла
            }
        }
    } else {
        // Случай 3: Ключа нет в текущем узле (он находится на нижних уровнях)
        if (x->leaf) {
            printf("Ключ %d отсутствует в дереве.\n", k);
            return;
        }
        
        // Флаг указывает, спускаемся ли мы в самого последнего (правого) ребенка
        bool flag = (i == x->n);
        
        // Если у ребенка мало ключей, превентивно «наполняем» его за счет соседей или слияния
        if (x->c[i]->n < T) {
            B_Tree_Fill(x, i);
        }
        
        // Если после слияния последний ребенок пропал (слился с левым), 
        // мы перенаправляем рекурсию в левый узел (c[i-1])
        if (flag && i > x->n) {
            B_Tree_Delete_Internal(x->c[i - 1], k);
        } else {
            B_Tree_Delete_Internal(x->c[i], k);
        }
    }
}

// Главная публичная функция удаления ключа из дерева. Процедура B-TREE-DELETE(T, k)
void B_Tree_Delete(BTree *T_tree, int k) {
    if (!T_tree->root) {
        printf("Дерево пустое.\n");
        return;
    }
    
    // Запускаем внутреннее рекурсивное удаление от корня
    B_Tree_Delete_Internal(T_tree->root, k);
    
    // Если после удаления корень полностью опустел (у него стало 0 ключей)
    if (T_tree->root->n == 0) {
        BTreeNode *tmp = T_tree->root;
        if (T_tree->root->leaf) {
            T_tree->root = NULL; // Если это был единственный лист, дерево теперь пустое
        } else {
            T_tree->root = T_tree->root->c[0]; // Первенец корня становится новым корнем. Высота дерева уменьшилась на 1.
        }
        free(tmp); // Освобождаем память старого корня
    }
}