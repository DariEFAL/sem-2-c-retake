#include "struct.h"

// Функция полного удаления поддерева из памяти (деаллокация узлов).
// Применяет постфиксный обход: сначала очищаем детей, потом сам узел.
void B_Tree_Free(BTreeNode *x) {
    if (x == NULL) return;

    // Если узел внутренний (не лист), сначала заходим во все его поддеревья
    if (!x->leaf) {
        // У узла с n ключами всегда строго n + 1 детей
        for (int i = 0; i <= x->n; i++) {
            B_Tree_Free(x->c[i]); // Рекурсивно освобождаем i-го ребенка
        }
    }

    // После того как все дети гарантированно удалены из памяти,
    // мы можем безопасно уничтожить сам текущий узел
    free(x);
}