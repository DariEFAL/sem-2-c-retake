// Бинарный поиск индекса внутри конкретного узла
int B_Tree_Find_Key_Index(BTreeNode *x, int k) {
    int low = 0;
    int high = x->n - 1;
    int result_idx = x->n; // По умолчанию, если ключ больше всех, возвращаем индекс x->n

    while (low <= high) {
        int mid = low + (high - low) / 2; // Находим середину массива ключей узла

        if (x->keys[mid] == k) {
            return mid; // Ключ найден ровно на этой позиции!
        }
        
        if (x->keys[mid] > k) {
            result_idx = mid; // Запоминаем текущую позицию как потенциальное место спуска
            high = mid - 1;   // Сужаем поиск в левую половину массива
        } else {
            low = mid + 1;    // Сужаем поиск в правую половину массива
        }
    }
    
    return result_idx; // Возвращает либо индекс найденного ключа, либо индекс ребенка для спуска
}

// Теперь работает на базе бинарного поиска внутри узла!
BTreeNode* B_Tree_Search(BTreeNode *x, int k, int *index_out) {
    if (x == NULL) return NULL;

    // ШАГ 1: Вместо медленного цикла while вызываем наш бинарный поиск.
    // За O(log t) мы мгновенно узнаем точный индекс i.
    int i = B_Tree_Find_Key_Index(x, k);
    
    // ШАГ 2: Проверяем, нашел ли бинарный поиск именно наш ключ.
    // Мы должны убедиться, что индекс i не вылетел за границы массива (i < x->n)
    // и что ключ в массиве действительно равен искомому k.
    if (i < x->n && k == x->keys[i]) {
        *index_out = i; // Сохраняем позицию ключа внутри узла для вызывающей программы
        return x;       // Возвращаем указатель на сам узел, где лежит ключ
    }
    
    // ШАГ 3: Если ключ в этом узле не найден, смотрим, можно ли идти глубже.
    if (x->leaf) {
        // Если текущий узел — лист, то спускаться больше некуда. Ключа в дереве нет.
        return NULL; 
    } else {
        // Если это внутренний узел, рекурсивно прыгаем к ребенку c[i].
        // Благодаря бинарному поиску, индекс i гарантированно указывает на правильное поддерево!
        return B_Tree_Search(x->c[i], k, index_out);
    }
}