#include "struct.h"

// Функция иерархического вывода B-дерева на экран.
// x - текущий узел, level - текущий уровень вложенности (используется для отступов).
// При первом вызове передается: B_Tree_Print(tree->root, 0);
void B_Tree_Print(BTreeNode *x, int level) {
    if (x == NULL) return;

    int i;
    // 1. Сначала рекурсивно печатаем самых правых детей (верхняя часть вывода)
    if (!x->leaf) {
        B_Tree_Print(x->c[x->n], level + 1);
    }

    // 2. Печатаем ключи текущего узла с разделением на поддеревья
    for (i = x->n - 1; i >= 0; i--) {
        // Делаем отступ в зависимости от уровня, на котором находится узел
        for (int j = 0; j < level; j++) {
            printf("    "); // 4 пробела на каждый уровень глубины
        }

        // Выводим ключ. Символы [ ] показывают границы одного узла.
        // Если в узле несколько ключей, они выведутся друг за другом с одинаковым отступом.
        printf("[%d]\n", x->keys[i]);

        // Рекурсивно печатаем ребенка, который находится слева от текущего ключа
        if (!x->leaf) {
            B_Tree_Print(x->c[i], level + 1);
        }
    }
}