#include "struct.h"

// Разделение переполненного ребенка c[i] у узла x. Процедура B-TREE-SPLIT-CHILD(x, i)
void B_Tree_Split_Child(BTreeNode *x, int i) {
    BTreeNode *y = x->c[i];          // y — это полный узел (содержит 2t - 1 ключей)
    BTreeNode *z = B_Tree_Create_Node(y->leaf); // z — новый узел, который заберет правую половину y
    
    // Новый узел z получает ровно (t - 1) верхних ключей из y
    z->n = T - 1;
    for (int j = 0; j < T - 1; j++) {
        z->keys[j] = y->keys[j + T];
    }
    
    // Если y не лист, то z также забирает себе его (t) правых детей
    if (!y->leaf) {
        for (int j = 0; j < T; j++) {
            z->c[j] = y->c[j + T];
        }
    }
    
    // Узел y теперь урезан, у него остается ровно (t - 1) ключей
    y->n = T - 1;
    
    // В родительском узле x освобождаем место под указатель на новый узел z
    for (int j = x->n; j >= i + 1; j--) {
        x->c[j + 1] = x->c[j];
    }
    x->c[i + 1] = z; // Привязываем новый узел z к родителю x
    
    // В родительском узле x сдвигаем ключи, чтобы освободить место под медианный ключ
    for (int j = x->n - 1; j >= i; j--) {
        x->keys[j + 1] = x->keys[j];
    }
    // Медианный (центральный) ключ из y поднимается в родительский узел x
    x->keys[i] = y->keys[T - 1];
    x->n = x->n + 1; // У родителя стало на 1 ключ больше
}

// Публичный метод вставки ключа. Процедура B-TREE-INSERT(T, k)
void B_Tree_Insert(BTree *T_tree, int k) {
    BTreeNode *r = T_tree->root;
    
    // Если корень полностью заполнен — дерево должно вырасти в высоту
    if (r->n == MAX_KEYS) {
        BTreeNode *s = B_Tree_Create_Node(false); // Создаем новый пустой корень
        T_tree->root = s;
        s->c[0] = r;                           // Старый корень становится первым ребенком нового
        B_Tree_Split_Child(s, 0);              // Делим старый корень напополам
        B_Tree_Insert_Nonfull(s, k);           // Вставляем ключ в уже неполный новый корень
    } else {
        // Если корень не заполнен, просто запускаем стандартную вставку
        B_Tree_Insert_Nonfull(r, k);              
    }
}

// Вставка в узел x, который гарантированно НЕ заполнен до конца. B-TREE-INSERT-NONFULL(x, k)
void B_Tree_Insert_Nonfull(BTreeNode *x, int k) {
    int i = x->n - 1;
    
    if (x->leaf) {
        // Если мы в листе, просто сдвигаем все элементы, которые больше k, вправо
        while (i >= 0 && k < x->keys[i]) {
            x->keys[i + 1] = x->keys[i];
            i--;
        }
        x->keys[i + 1] = k; // Сажаем ключ на его законное место
        x->n = x->n + 1;
    } else {
        // Если это внутренний узел, ищем, в какого ребенка нужно спускаться
        while (i >= 0 && k < x->keys[i]) {
            i--;
        }
        i++; // Индекс ребенка c[i]
        
        // Превентивный шаг: если ребенок, куда мы хотим пойти, заполнен — делим его прямо сейчас!
        if (x->c[i]->n == MAX_KEYS) {
            B_Tree_Split_Child(x, i);
            // После деления медианный ключ ушел вверх в узел x.
            // Проверяем, не нужно ли нам теперь изменить курс и пойти в правый осколок (z)
            if (k > x->keys[i]) {
                i++;
            }
        }
        // Рекурсивно спускаемся ниже
        B_Tree_Insert_Nonfull(x->c[i], k);
    }
}
