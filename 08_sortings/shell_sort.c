#include <stdio.h>

void shellSort(int arr[], int n) {
    // Начинаем с большого шага и уменьшаем его вдвое на каждой итерации
    for (int gap = n / 2; gap > 0; gap /= 2) {
        // Выполняем сортировку вставками для элементов на расстоянии gap
        for (int i = gap; i < n; i++) {
            int temp = arr[i];
            int j;
            for (j = i; j >= gap && arr[j - gap] > temp; j -= gap) {
                arr[j] = arr[j - gap];
            }
            arr[j] = temp;
        }
    }
}

int main() {
    int arr[] = {41, 12, 5, 2, 19, 32, 1};
    int n = sizeof(arr) / sizeof(arr[0]);
    
    printf("\nИсходный массив (Шелл): ");
    for(int i=0; i<n; i++) printf("%d ", arr[i]);
    
    shellSort(arr, n);
    
    printf("\nОтсортированный массив: ");
    for(int i=0; i<n; i++) printf("%d ", arr[i]);
    printf("\n");
    return 0;
}

/*
Для чего используется: Улучшенная модификация сортировки вставками. 
Применяется, когда в распоряжении мало памяти, а производительности обычной вставки O(n^2) недостаточно.
Хорошо работает на средних объемах данных. 
Сложность:
    Лучшая: O(nlog n)
    Средняя/Худшая: Зависит от шага (последовательности промежутков). 
                    Обычно оценивается от O(n^{1.25}) до O(n^2). 
                    Для классической последовательности Шелла худшая — O(n^2). 
    Память: O(1) (сортирует на месте). 
Стабильность: Нестабильная. 

gcc shell_sort.c -o shell_sort
./shell_sort
*/